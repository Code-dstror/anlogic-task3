`timescale 1ns / 1ps
`include "pcie_protocol_v1.vh"

// 解码DDR时钟域的帧起始数据和结束令牌
module ordered_frame_egress #(
    parameter integer CONTEXT_ENABLE = 0,
    parameter integer WRITE_TAG_ENABLE = 0,
    parameter integer RECORD_EXTENSION_ENABLE = 0,
    parameter integer RECORD_EXTENSION_WIDTH = 1024,
    parameter integer MASK_CONTEXT_ENABLE = 0,
    parameter integer EXTENSION_RAM_ENABLE = 0
) (
    // 时钟与复位
    input wire i_clk,
    input wire i_rst_n,

    // 输入令牌流
    input wire [146:0] i_token_data,
    input wire i_token_valid,
    output wire o_token_ready,
    output wire o_token_pending,

    // 帧起始与元数据
    output wire o_start_valid,
    input wire i_start_ready,
    output wire [31:0] o_capture_id,
    output wire [15:0] o_width,
    output wire [15:0] o_height,
    output wire [63:0] o_timestamp_ns,
    output reg [31:0] o_session_id, o_mode_epoch,
    output reg o_camera_id,
    output reg [7:0] o_quality, o_format,
    output reg [31:0] o_write_tag,
    output reg o_start_mask,
    output reg [2:0] o_start_source_type,

    // JPEG载荷流
    output wire [127:0] o_jpeg_tdata,
    output wire [15:0] o_jpeg_tkeep,
    output wire o_jpeg_tlast,
    output wire o_jpeg_tvalid,
    input wire i_jpeg_tready,

    // 帧结束结果
    output wire o_result_valid,
    input wire i_result_ready,
    output wire [31:0] o_result_id,
    output wire o_result_ok,
    output wire [24:0] o_result_length,
    output wire [7:0] o_result_error,
    output wire [7:0] o_result_quality,
    output wire [31:0] o_result_epoch,

    // Complete extension is held until this real consumer accepts it.
    output reg [RECORD_EXTENSION_WIDTH-1:0] o_record_extension,
    output wire o_record_extension_valid,
    input wire i_record_extension_ready,

    // Complete staging lease is retained until the next real START.
    output wire o_extension_shape_valid,
    input wire i_extension_read_enable,
    input wire [8:0] i_extension_read_index,
    output wire [39:0] o_extension_read_data,

    // 协议故障
    output reg o_protocol_fault // 发现孤立或非法令牌时置位
);
    generate if(RECORD_EXTENSION_WIDTH!=1024 && RECORD_EXTENSION_WIDTH!=3072 && RECORD_EXTENSION_WIDTH!=16384) begin : invalid_record_width
        RECORD_EXTENSION_REQUIRES_1024_3072_OR_16384 u_invalid_record_width();
    end endgenerate
    generate if(RECORD_EXTENSION_ENABLE!=0 && (CONTEXT_ENABLE==0 || WRITE_TAG_ENABLE==0)) begin : invalid_extension_profile
        TD_ORDERED_RECORD_EXTENSION_REQUIRES_CONTEXT_AND_WRITE_TAG u_invalid_configuration();
    end endgenerate
    generate if(MASK_CONTEXT_ENABLE!=0 && (CONTEXT_ENABLE==0 || WRITE_TAG_ENABLE==0)) begin : invalid_mask_profile
        TD_ORDERED_MASK_REQUIRES_CONTEXT_AND_WRITE_TAG u_invalid_configuration();
    end endgenerate
    localparam integer EXTENSION_FLITS=RECORD_EXTENSION_WIDTH/128;
    localparam integer EXTENSION_INDEX_WIDTH=RECORD_EXTENSION_WIDTH==16384 ? 7 : (RECORD_EXTENSION_WIDTH==3072 ? 5 : 3);
    `include "pcie_record_v3_validate.vh"
    // The generated byte offsets are relative to the full192-byte record.
    function extension_matches;
        input [RECORD_EXTENSION_WIDTH-1:0] value;
        input [31:0] session_value,epoch_value,sequence_value;
        input camera_value;
        reg [2047:0] sparse;
        begin
            sparse=value >> 1024;
            extension_matches=
                value[31:0]==`PCIE_RECORD_V2_EXTENSION_MAGIC &&
                value[47:32]==`PCIE_RECORD_V2_SCHEMA_VERSION &&
                value[48+`PCIE_RECORD_V2_FLAG_SOURCE_IDENTITY] &&
                value[63:60]==0 &&
                value[95:64]==session_value && value[127:96]==epoch_value &&
                value[159:128]==sequence_value && value[167:160]=={7'd0,camera_value} &&
                value[255:192]==0 && value[959:947]==0 && value[1023:960]==0 &&
                (RECORD_EXTENSION_WIDTH==1024 || sparse==0 || sparse_v3_valid(sparse));
        end
    endfunction
    localparam [7:0] E_FENCE_INCONSISTENT = 8'he3, E_CONTEXT_MISMATCH = 8'he4;
    reg active, context_pending;
    reg [31:0] context_sequence;
    reg last_seen; // 错误 FENCE 可缺少 TLAST，成功 FENCE 不可缺少
    reg [31:0] capture_id;
    reg [15:0] frame_width,frame_height;
    reg [63:0] frame_timestamp;
    reg extension_started,extension_complete,extension_accepted;
    reg extension_input_complete;
    reg [EXTENSION_INDEX_WIDTH-1:0] extension_index;
    reg [25:0] observed_bytes;
    reg [146:0] token_data;
    reg token_valid;
    reg token_is_context_or_extension,token_is_start,token_is_jpeg,token_is_result;
    reg decoded_start_match,decoded_extension_index_match;
    reg [5:0] extension_head_checks;
    reg [4:0] beat_bytes;
    // The input replaces a valid token only on its actual handshake. The
    // held kind predicts the successor without feeding READY into the match.
    wire replacing_context=token_valid && !active && token_is_context_or_extension;
    wire replacing_start=token_valid && !active && token_is_start;
    wire replacing_extension=token_valid && active && token_is_context_or_extension;
    wire replacing_result=token_valid && active && token_is_result;
    wire [EXTENSION_INDEX_WIDTH-1:0] incremented_extension_index=extension_index+1'b1;
    wire [EXTENSION_INDEX_WIDTH-1:0] next_extension_index=
        replacing_start ? {EXTENSION_INDEX_WIDTH{1'b0}} :
        (replacing_extension ? incremented_extension_index : extension_index);
    wire [1:0] input_kind=i_token_data[146:145];
    assign o_token_pending=token_valid;
    wire [1:0] count_pair0={1'b0,i_token_data[128]}+{1'b0,i_token_data[129]};
    wire [1:0] count_pair1={1'b0,i_token_data[130]}+{1'b0,i_token_data[131]};
    wire [1:0] count_pair2={1'b0,i_token_data[132]}+{1'b0,i_token_data[133]};
    wire [1:0] count_pair3={1'b0,i_token_data[134]}+{1'b0,i_token_data[135]};
    wire [1:0] count_pair4={1'b0,i_token_data[136]}+{1'b0,i_token_data[137]};
    wire [1:0] count_pair5={1'b0,i_token_data[138]}+{1'b0,i_token_data[139]};
    wire [1:0] count_pair6={1'b0,i_token_data[140]}+{1'b0,i_token_data[141]};
    wire [1:0] count_pair7={1'b0,i_token_data[142]}+{1'b0,i_token_data[143]};
    wire [2:0] count_group0={1'b0,count_pair0}+{1'b0,count_pair1};
    wire [2:0] count_group1={1'b0,count_pair2}+{1'b0,count_pair3};
    wire [2:0] count_group2={1'b0,count_pair4}+{1'b0,count_pair5};
    wire [2:0] count_group3={1'b0,count_pair6}+{1'b0,count_pair7};
    wire [3:0] count_half0={1'b0,count_group0}+{1'b0,count_group1};
    wire [3:0] count_half1={1'b0,count_group2}+{1'b0,count_group3};
    always @(posedge i_clk or negedge i_rst_n) begin
        if(!i_rst_n) begin
            token_valid<=0;beat_bytes<=0;context_sequence<=0;decoded_start_match<=0;
            token_is_context_or_extension<=0;token_is_start<=0;token_is_jpeg<=0;token_is_result<=0;
            decoded_extension_index_match<=0;extension_head_checks<=0;
        end
        else if(o_token_ready)begin
            // A free local slot clocks the snapshot. The separately stored
            // input VALID commits it, keeping FIFO validity off the wide CE.
            token_valid<=i_token_valid;
            token_data<=i_token_data;
            token_is_context_or_extension<=input_kind==2'b11;
            token_is_start<=input_kind==2'b10;
            token_is_jpeg<=input_kind==2'b00;
            token_is_result<=input_kind==2'b01;
            beat_bytes<={1'b0,count_half0}+{1'b0,count_half1};
            // A following START can use this sequence on its next edge.
            if(i_token_valid && CONTEXT_ENABLE && input_kind==2'b11 && (!active || replacing_result))
                context_sequence<=i_token_data[104:73];
            decoded_start_match<=!CONTEXT_ENABLE ||
                ((context_pending || replacing_context) && context_sequence==i_token_data[31:0]);
            decoded_extension_index_match<=i_token_data[144:128]==
                {{(17-EXTENSION_INDEX_WIDTH){1'b0}},next_extension_index};
            // Hold narrow compare results beside the same sampled flit.
            extension_head_checks[0]<=i_token_data[31:0]==`PCIE_RECORD_V2_EXTENSION_MAGIC;
            extension_head_checks[1]<=i_token_data[47:32]==`PCIE_RECORD_V2_SCHEMA_VERSION &&
                i_token_data[48+`PCIE_RECORD_V2_FLAG_SOURCE_IDENTITY] && i_token_data[63:60]==0;
            extension_head_checks[2]<=i_token_data[79:64]==o_session_id[15:0];
            extension_head_checks[3]<=i_token_data[95:80]==o_session_id[31:16];
            extension_head_checks[4]<=i_token_data[111:96]==o_mode_epoch[15:0];
            extension_head_checks[5]<=i_token_data[127:112]==o_mode_epoch[31:16];
        end
    end

    wire [7:0] context_format=token_data[112:105];
    wire mask_marker=context_format[7:4]==4'ha && context_format[3] && context_format[1:0]!=0;
    wire mask_context_bad=MASK_CONTEXT_ENABLE!=0 && context_format!=8'd1 && !mask_marker;
    wire enabled = i_rst_n && !o_protocol_fault;
    wire fence_consistent = (capture_id == token_data[31:0]) &&
                            (observed_bytes == token_data[91:66]) &&
                            (!token_data[57] ||
                             (observed_bytes == {1'b0, token_data[56:32]} &&
                              last_seen));

    wire start_context_match = decoded_start_match;
    wire result_context_match = !CONTEXT_ENABLE ||
                               (o_result_quality == o_quality && o_result_epoch == o_mode_epoch);
    wire context_offer=!active && token_is_context_or_extension && CONTEXT_ENABLE && !context_pending;
    wire start_offer=!active && token_is_start && start_context_match;
    wire jpeg_offer=active && token_is_jpeg && !last_seen && !extension_started;
    wire result_offer=active && token_is_result && (!RECORD_EXTENSION_ENABLE || extension_accepted);

    // 仅在活动帧和目的端就绪时交付解码数据
    assign o_start_valid = enabled && token_valid && start_offer;
    assign o_capture_id = active ? capture_id : token_data[31:0];
    assign o_width = active ? frame_width : token_data[47:32];
    assign o_height = active ? frame_height : token_data[63:48];
    assign o_timestamp_ns = active ? frame_timestamp : token_data[127:64];
    assign o_jpeg_tvalid = enabled && token_valid && jpeg_offer;
    assign o_jpeg_tdata = token_data[127:0];
    assign o_jpeg_tkeep = token_data[143:128];
    assign o_jpeg_tlast = token_data[144];
    assign o_result_valid = enabled && token_valid && result_offer;
    assign o_result_id = token_data[31:0];
    assign o_result_length = token_data[56:32];
    assign o_result_quality = CONTEXT_ENABLE ? token_data[99:92] : 8'd0;
    assign o_result_epoch = CONTEXT_ENABLE ? token_data[131:100] : 32'd0;
    assign o_result_ok = token_data[57] && fence_consistent && result_context_match;
    assign o_result_error = !fence_consistent ? E_FENCE_INCONSISTENT :
                            !result_context_match ? E_CONTEXT_MISMATCH : token_data[65:58];

    assign o_record_extension_valid=i_rst_n && RECORD_EXTENSION_ENABLE && active &&
                                    extension_complete && !extension_accepted;
    wire extension_index_match=decoded_extension_index_match;
    wire extension_head_match=extension_started || (&extension_head_checks);
    wire [RECORD_EXTENSION_WIDTH-1:0] complete_extension={token_data[127:0],o_record_extension[RECORD_EXTENSION_WIDTH-129:0]};

    wire staging_ready,staging_complete,staging_good;
    wire extension_ok=!extension_input_complete && extension_index_match && extension_head_match;
    wire extension_offer=active && token_is_context_or_extension && extension_ok;
    wire staging_input_valid=enabled && token_valid && extension_offer;
    wire extension_take=RECORD_EXTENSION_ENABLE && extension_offer && staging_ready;
    wire extension_fire=enabled && token_valid && extension_take;
    assign o_token_ready=enabled && (!token_valid || context_offer || extension_take ||
        (start_offer && i_start_ready) || (jpeg_offer && i_jpeg_tready) ||
        (result_offer && i_result_ready));
    generate if(EXTENSION_RAM_ENABLE!=0)begin : g_staging
        // Flit data and first-flit checks share the same capture enable.
        ddr_extension_staging_ram #(.RECORD_EXTENSION_WIDTH(RECORD_EXTENSION_WIDTH),
            .FIRST_FLIT_PRECHECKED(1)) u_staging (
            .i_clk(i_clk),.i_rst_n(i_rst_n),.i_begin(o_start_valid && i_start_ready),
            .i_session(o_session_id),.i_epoch(o_mode_epoch),.i_sequence(capture_id),.i_camera(o_camera_id),
            .s_data(token_data[127:0]),.s_valid(staging_input_valid),
            .s_last(extension_index==EXTENSION_FLITS-1),.s_ready(staging_ready),
            .o_complete(staging_complete),.o_shape_valid(staging_good),
            .i_read_enable(i_extension_read_enable),.i_read_index(i_extension_read_index),
            .o_read_data(o_extension_read_data));
        assign o_extension_shape_valid=staging_good;
    end else begin : g_parallel_extension
        assign staging_ready=1'b1;assign staging_complete=1'b0;assign staging_good=1'b0;
        assign o_extension_shape_valid=1'b0;assign o_extension_read_data=40'd0;
    end endgenerate

    // 跟踪帧序号字节数和结束令牌的匹配结果
    always @(posedge i_clk or negedge i_rst_n) begin
        if (!i_rst_n) begin
            active <= 1'b0; context_pending <= 0;
            o_session_id <= 0; o_mode_epoch <= 0; o_camera_id <= 0; o_quality <= 0; o_format <= 0;
            o_write_tag <= 0;
            o_start_mask<=0;o_start_source_type<=0;
            last_seen <= 1'b0;
            capture_id <= 32'd0;frame_width<=0;frame_height<=0;frame_timestamp<=0;
            extension_started<=0;extension_complete<=0;extension_accepted<=0;extension_index<=0;extension_input_complete<=0;
            observed_bytes <= 26'd0;
            o_protocol_fault <= 1'b0;
        end else begin
            // An already presented extension survives later protocol quarantine.
            if(o_record_extension_valid && i_record_extension_ready)extension_accepted<=1;
            if (enabled) begin
            if (token_valid &&
                ((token_is_context_or_extension && !active && (!CONTEXT_ENABLE || context_pending ||
                                   (!WRITE_TAG_ENABLE && token_data[144:113] != 0))) ||
                 (!active && !token_is_context_or_extension && !start_offer) ||
                 (token_is_context_or_extension && !active && MASK_CONTEXT_ENABLE!=0 && mask_context_bad) ||
                 (active && token_is_start) ||
                 (active && token_is_jpeg && !jpeg_offer) ||
                 (active && token_is_context_or_extension && (!RECORD_EXTENSION_ENABLE || !extension_ok)) ||
                 (active && token_is_result && RECORD_EXTENSION_ENABLE && !extension_input_complete)))
                o_protocol_fault <= 1'b1;
            if (token_valid && context_offer) begin
                context_pending <= 1;
                o_session_id <= token_data[31:0]; o_mode_epoch <= token_data[63:32];
                o_camera_id <= token_data[64]; o_quality <= token_data[72:65]; o_format <= token_data[112:105];
                if(MASK_CONTEXT_ENABLE!=0)begin
                    o_start_mask<=mask_marker;
                    o_start_source_type<=mask_marker ? context_format[2:0] : 3'd0;
                    o_format<=8'd1;
                end
                o_write_tag <= WRITE_TAG_ENABLE ? token_data[144:113] : 32'd0;
            end
            if (o_start_valid && i_start_ready) begin
                active <= 1'b1; context_pending <= 0;
                last_seen <= 1'b0;
                capture_id <= o_capture_id;frame_width<=o_width;frame_height<=o_height;frame_timestamp<=o_timestamp_ns;
                extension_started<=0;extension_complete<=0;extension_accepted<=0;extension_index<=0;extension_input_complete<=0;
                observed_bytes <= 26'd0;
            end
            if (o_jpeg_tvalid && i_jpeg_tready) begin
                observed_bytes <= observed_bytes + beat_bytes;
                if (o_jpeg_tlast) last_seen <= 1'b1;
            end
            if(extension_fire)begin
                extension_started<=1;
                if(extension_index==EXTENSION_FLITS-1)begin
                    extension_input_complete<=1;
                    if(EXTENSION_RAM_ENABLE==0)begin
                        if(extension_matches(complete_extension,o_session_id,o_mode_epoch,capture_id,o_camera_id))
                            extension_complete<=1;
                        else o_protocol_fault<=1;
                    end
                end else extension_index<=incremented_extension_index;
            end
            // A queued legal FENCE waits through the final physical staging write.
            if(EXTENSION_RAM_ENABLE!=0 && active && extension_input_complete &&
               !extension_complete && staging_complete)begin
                if(staging_good)extension_complete<=1;
                else o_protocol_fault<=1;
            end
            if (o_result_valid && i_result_ready) begin
                active <= 1'b0;
                last_seen <= 1'b0;
                if (!fence_consistent)
                    o_protocol_fault <= 1'b1;
            end
            end
        end
    end
    // Constant part-selects expose one clock enable per physical 128-bit bank.
    // These are the original START clear and accepted extension-token events.
    wire extension_bank_clear = enabled && o_start_valid && i_start_ready;
    genvar extension_bank;
    generate if(EXTENSION_RAM_ENABLE!=0)begin : g_no_parallel_bank
        // The inactive legacy vector is a constant and has no payload storage.
        always @(posedge i_clk or negedge i_rst_n)begin
            if(!i_rst_n)o_record_extension<=0;
            else o_record_extension<=0;
        end
    end else for (extension_bank=0; extension_bank<EXTENSION_FLITS;
                  extension_bank=extension_bank+1) begin : g_extension_bank
        localparam [EXTENSION_INDEX_WIDTH-1:0] BANK_INDEX = extension_bank;
        always @(posedge i_clk or negedge i_rst_n) begin
            if (!i_rst_n)
                o_record_extension[extension_bank*128+:128] <= 128'd0;
            else if (extension_bank_clear)
                o_record_extension[extension_bank*128+:128] <= 128'd0;
            else if (extension_fire && extension_index == BANK_INDEX)
                o_record_extension[extension_bank*128+:128] <= token_data[127:0];
        end
    end endgenerate
endmodule
