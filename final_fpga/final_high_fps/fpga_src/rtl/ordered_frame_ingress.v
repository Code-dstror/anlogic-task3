`timescale 1ns / 1ps
`include "pcie_protocol_v1.vh"

// 将JPEG帧起始数据和结果编码为有序令牌
module ordered_frame_ingress #(
    parameter integer CONTEXT_ENABLE = 0,
    parameter integer WRITE_TAG_ENABLE = 0,
    parameter integer RECORD_EXTENSION_ENABLE = 0,
    parameter integer RECORD_EXTENSION_WIDTH = 1024,
    parameter integer BORROW_EXTENSION = 1,
    parameter integer STREAM_EXTENSION = 1,
    parameter integer MASK_CONTEXT_ENABLE = 0,
    parameter integer SEPARATE_DATA_RESET = 0
) (
    // 时钟与复位
    input wire i_clk,
    input wire i_rst_n,

    // 帧起始与元数据
    input wire i_start_valid,
    output wire o_start_ready,
    input wire [31:0] i_capture_id,
    input wire [15:0] i_width,
    input wire [15:0] i_height,
    input wire [63:0] i_timestamp_ns,
    input wire [31:0] i_session_id, i_mode_epoch,
    input wire i_camera_id,
    input wire [7:0] i_quality, i_format,
    input wire [31:0] i_write_tag,
    input wire i_start_mask,
    input wire [2:0] i_start_source_type,

    // JPEG载荷流
    input wire [127:0] i_jpeg_tdata,
    input wire [15:0] i_jpeg_tkeep,
    input wire i_jpeg_tlast,
    input wire i_jpeg_tvalid,
    output wire o_jpeg_tready,

    // 帧结束结果
    input wire i_result_valid,
    output wire o_result_ready,
    input wire [31:0] i_result_id,
    input wire i_result_ok,
    input wire [24:0] i_result_length,
    input wire [7:0] i_result_error,
    input wire [7:0] i_result_quality,
    input wire [31:0] i_result_epoch,

    // Optional v2 extension and source-domain quarantine.
    input wire [2047:0] i_record_extension,
    input wire i_record_extension_valid,
    output wire o_record_extension_ready,
    input wire [127:0] i_extension_stream_data,
    input wire i_extension_stream_valid,
    output wire o_extension_stream_ready,
    output wire o_extension_stream_start,
    output reg o_protocol_fault,

    // 输出令牌流
    output reg [146:0] o_token_data, // 统一承载起始数据和结束令牌
    output wire o_token_valid,
    input wire i_token_ready,
    // 可选的同域数据资格，须与 i_rst_n 在同一个上升沿前解除复位。
    input wire i_data_rst_n
);
    generate if(RECORD_EXTENSION_WIDTH!=16384 || STREAM_EXTENSION!=1 || BORROW_EXTENSION!=1) begin : invalid_record_width
        RECORD_EXTENSION_REQUIRES_16384_BORROWED_STREAM u_invalid_record_width();
    end endgenerate
    generate if(RECORD_EXTENSION_ENABLE!=0 && (CONTEXT_ENABLE==0 || WRITE_TAG_ENABLE==0)) begin : invalid_extension_profile
        TD_ORDERED_RECORD_EXTENSION_REQUIRES_CONTEXT_AND_WRITE_TAG u_invalid_configuration();
    end endgenerate
    generate if(MASK_CONTEXT_ENABLE!=0 && (CONTEXT_ENABLE==0 || WRITE_TAG_ENABLE==0)) begin : invalid_mask_profile
        TD_ORDERED_MASK_REQUIRES_CONTEXT_AND_WRITE_TAG u_invalid_configuration();
    end endgenerate
    localparam integer EXTENSION_FLITS=RECORD_EXTENSION_WIDTH/128;
    localparam integer EXTENSION_INDEX_WIDTH=7;
    `include "pcie_record_v3_validate.vh"
    // The generated byte offsets are relative to the full192-byte record.
    function extension_matches;
        input [2047:0] value;
        input [31:0] session_value,epoch_value,sequence_value;
        input camera_value;
        reg [2047:0] sparse;
        begin
            sparse=value >> 1024;
            extension_matches=
                value[31:0]==`PCIE_RECORD_V2_EXTENSION_MAGIC &&
                value[47:32]==`PCIE_RECORD_V2_SCHEMA_VERSION &&
                value[48+`PCIE_RECORD_V2_FLAG_SOURCE_IDENTITY] &&
                value[63:60]==0 &&
                value[95:64]==session_value && value[127:96]==epoch_value &&
                value[159:128]==sequence_value && value[167:160]=={7'd0,camera_value} &&
                value[255:192]==0 && value[959:947]==0 && value[1023:960]==0 &&
                value[1055:1024]==`PCIE_RECORD_V4_SPARSE_MAGIC &&
                value[1063:1056]==`PCIE_RECORD_V4_SPARSE_SCHEMA &&
                value[1071:1064]==`PCIE_RECORD_V4_POINT_BYTES && value[1119:1104]<=303;
        end
    endfunction
    localparam [7:0] E_ID_MISMATCH = 8'he1, E_LENGTH_MISMATCH = 8'he2, E_CONTEXT_MISMATCH = 8'he4;
    reg active, context_sent;
    reg [127:0] start_payload;
    reg [31:0] frozen_epoch,frozen_session;
    reg frozen_camera;

    reg [73:0] frozen_result;
    wire [131:0] frozen_fence;
    reg extension_latched,extension_sent;
    reg [EXTENSION_INDEX_WIDTH-1:0] extension_index;
    reg [7:0] frozen_quality;
    wire result_context_match = !CONTEXT_ENABLE ||
        (i_result_quality == frozen_quality && i_result_epoch == frozen_epoch);
    reg [31:0] capture_id;
    reg [25:0] observed_bytes;
    // Extension ownership blocks JPEG and START acceptance until the FENCE
    // is really transferred. Reuse these stable frame-owned fields throughout.
    assign frozen_fence={frozen_result[73:34],observed_bytes,frozen_result[33:0],capture_id};
    reg [4:0] beat_bytes;
    reg [127:0] fence;
    integer k;

    // 起始数据和结束令牌共用同一有序输出流
    wire mask_context_legal=i_start_mask ? i_start_source_type[1:0]!=0 : i_format==8'd1;
    wire [7:0] context_format=MASK_CONTEXT_ENABLE!=0 && i_start_mask ?
        {4'ha,1'b1,i_start_source_type} : i_format;
    wire source_data_rst_n=SEPARATE_DATA_RESET!=0 ? i_data_rst_n : i_rst_n;
    wire source_enabled=source_data_rst_n && !o_protocol_fault &&
        (MASK_CONTEXT_ENABLE==0 || active || context_sent || !i_start_valid || mask_context_legal);
    assign o_token_valid = source_enabled &&
                           (active ? (RECORD_EXTENSION_ENABLE && extension_latched ?
                                     (extension_sent || i_extension_stream_valid) : (i_jpeg_tvalid || (!RECORD_EXTENSION_ENABLE && i_result_valid)))
                                   : (context_sent || i_start_valid));
    assign o_start_ready = source_enabled && !active && (!CONTEXT_ENABLE || context_sent) && i_token_ready;
    assign o_jpeg_tready = source_enabled && active && !extension_latched && i_token_ready;
    assign o_result_ready = source_enabled && active &&
                            (RECORD_EXTENSION_ENABLE ? extension_sent : !i_jpeg_tvalid) && i_token_ready;
    wire extension_available = source_enabled && RECORD_EXTENSION_ENABLE && active &&
                               !extension_latched && !i_jpeg_tvalid && i_result_valid;
    // Borrowed payload remains valid through the final real extension flit.
    // The actual FENCE is captured at inspection, before its later handshake.
    assign o_record_extension_ready = BORROW_EXTENSION ?
        (source_enabled && RECORD_EXTENSION_ENABLE && active && extension_latched &&
         !extension_sent && extension_index==EXTENSION_FLITS-1 && i_extension_stream_valid && i_token_ready) :
        extension_available;
    wire extension_begin=i_record_extension_valid && extension_available;
    wire [127:0] extension_word=i_extension_stream_data;
    assign o_extension_stream_start=extension_begin;
    assign o_extension_stream_ready=source_enabled && active && extension_latched && !extension_sent && i_token_ready;

    // 计算输入拍长度并构造帧结束令牌
    always @(*) begin
        beat_bytes = 0;
        for (k = 0; k < 16; k = k + 1)
            beat_bytes = beat_bytes + i_jpeg_tkeep[k];
        fence = 128'd0;
        fence[31:0] = capture_id;
        fence[56:32] = i_result_length;
        fence[57] = i_result_ok && (i_result_id == capture_id) &&
                    (observed_bytes == {1'b0, i_result_length}) && result_context_match;
        fence[65:58] = (i_result_id != capture_id) ? E_ID_MISMATCH :
                       ((i_result_ok &&
                         observed_bytes != {1'b0, i_result_length}) ?
                        E_LENGTH_MISMATCH : (!result_context_match ? E_CONTEXT_MISMATCH : i_result_error));
        fence[91:66] = observed_bytes;
        if (!active && CONTEXT_ENABLE && !context_sent)
            o_token_data = {2'b11,WRITE_TAG_ENABLE ? i_write_tag : 32'd0,
                            context_format,i_capture_id,i_quality,i_camera_id,i_mode_epoch,i_session_id};
        else if (!active)
            o_token_data = {2'b10,17'd0,CONTEXT_ENABLE ? start_payload :
                            {i_timestamp_ns,i_height,i_width,i_capture_id}};
        else if (RECORD_EXTENSION_ENABLE && extension_latched && !extension_sent)
            o_token_data = {2'b11,{(17-EXTENSION_INDEX_WIDTH){1'b0}},extension_index,extension_word};
        else if (RECORD_EXTENSION_ENABLE && extension_sent)
            o_token_data = {2'b01,13'd0,frozen_fence};
        else if (i_jpeg_tvalid)
            o_token_data = {2'b00, i_jpeg_tlast, i_jpeg_tkeep, i_jpeg_tdata};
        else if (CONTEXT_ENABLE)
            o_token_data = {2'b01,13'd0,i_result_epoch,i_result_quality,fence[91:0]};
        else
            o_token_data = {2'b01, 17'd0, fence};
    end

    // Frame payload is written before its corresponding validity is published.
    // Keep cold reset on ownership/validity below, not these data FFs; removing
    // their ASR loads avoids the measured source-release removal paths.
    always @(posedge i_clk) begin
        if (!o_protocol_fault) begin
            if (CONTEXT_ENABLE && !active && !context_sent && i_start_valid && o_token_valid && i_token_ready) begin
                start_payload <= {i_timestamp_ns,i_height,i_width,i_capture_id};
                frozen_epoch <= i_mode_epoch; frozen_quality <= i_quality;
                frozen_session<=i_session_id;frozen_camera<=i_camera_id;
            end
            if (!active && o_token_valid && i_token_ready && (!CONTEXT_ENABLE || context_sent))
                observed_bytes <= 26'd0;
            if (i_jpeg_tvalid && o_jpeg_tready)
                observed_bytes <= observed_bytes + beat_bytes;
            if(extension_begin && extension_matches(i_record_extension,frozen_session,frozen_epoch,capture_id,frozen_camera))
                frozen_result<={i_result_epoch,i_result_quality,fence[65:32]};
        end
    end
    // 仅在令牌被接收时推进帧状态和字节计数
    always @(posedge i_clk or negedge i_rst_n) begin
        if (!i_rst_n) begin
            active <= 1'b0; context_sent <= 0;
            extension_latched<=0;extension_sent<=0;extension_index<=0;o_protocol_fault<=0;
            capture_id <= 32'd0;
        end else if (!o_protocol_fault) begin
            if(MASK_CONTEXT_ENABLE!=0 && i_start_valid && !active && !context_sent && !mask_context_legal)
                o_protocol_fault<=1;
            if (CONTEXT_ENABLE && !active && !context_sent && i_start_valid && o_token_valid && i_token_ready) begin
                context_sent <= 1;
            end
            if (!active && o_token_valid && i_token_ready && (!CONTEXT_ENABLE || context_sent)) begin
                active <= 1'b1;
                capture_id <= CONTEXT_ENABLE ? start_payload[31:0] : i_capture_id;
                context_sent <= 0;
            end
            if(extension_begin)begin
                if(!extension_matches(i_record_extension,frozen_session,frozen_epoch,capture_id,frozen_camera))
                    o_protocol_fault<=1;
                else begin
                    extension_latched<=1;extension_sent<=0;extension_index<=0;
                end
            end
            if(RECORD_EXTENSION_ENABLE && extension_latched && o_token_valid && i_token_ready)begin
                if(!extension_sent)begin
                    if(extension_index==EXTENSION_FLITS-1)extension_sent<=1;
                    else extension_index<=extension_index+1'b1;
                end else begin active<=0;extension_latched<=0;extension_sent<=0;extension_index<=0;end
            end else if (!RECORD_EXTENSION_ENABLE && i_result_valid && o_result_ready)
                active <= 1'b0;
        end
    end
endmodule
