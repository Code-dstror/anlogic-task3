`timescale 1ns/1ps

// Retained DFI authority for two deterministic LONG/SHORT banks. The writer
// borrows its descriptor through s_begin_ready; no complete tuple is copied.
module hdr_pair_bank_owner #(
    parameter integer WIDTH=1920, HEIGHT=1080,
    parameter integer CAMERA_COUNT=1, DOL2_ENABLE=0, CAMERA_ID=0
) (
    input wire i_clk,i_identity_rst_n,i_stop,i_transport_fault,
    input wire [63:0] i_now,
    input wire i_config_valid,
    output wire o_config_ready,
    input wire [31:0] i_session,i_epoch,i_max_delta,i_max_wait,i_max_age,
    input wire [2:0] i_ratio_log2,input wire i_hdr_enable,
    output wire o_config_error,
    input wire [383:0] s_frame,
    input wire s_begin_valid,
    output wire s_begin_ready,o_begin_accepted,
    output wire [1:0] o_capture_slot,
    output wire [31:0] o_capture_generation,
    output wire [63:0] o_capture_lease,
    input wire i_begin_member,
    input wire i_finish1_valid,i_finish1_ok,
    output wire o_finish1_ready,
    input wire i_finish_valid,i_finish_ok,
    output wire o_finish_ready,
    output wire o_pair_valid,
    input wire i_pair_ready,
    output wire o_pair_bank,
    output wire [63:0] o_pair_id,
    input wire i_release_valid,i_release_bank,
    input wire [63:0] i_release_pair_id,
    input wire i_read_quiet,i_write_quiet,i_ticket_released,
    output wire o_release_ready,
    input wire i_directory_read_valid,
    input wire [1:0] i_directory_read_slot,
    output wire o_directory_read_ready,
    output wire [31:0] m_directory_data,
    output wire [3:0] m_directory_word,
    output wire m_directory_valid,m_directory_last,
    input wire m_directory_ready,
    output wire o_empty,o_capture_busy,o_exhausted,o_fault,
    output wire [5:0] o_bank_states,
    output wire [31:0] o_reject_count,o_expire_count
);
    generate if(DOL2_ENABLE!=0)begin:g_dol2
        hdr_pair_bank_owner_dual #(.CAMERA_ID(CAMERA_ID),.WIDTH(WIDTH),.HEIGHT(HEIGHT),.CAMERA_COUNT(CAMERA_COUNT)) impl(
            .i_clk(i_clk),
            .i_identity_rst_n(i_identity_rst_n),
            .i_stop(i_stop),
            .i_transport_fault(i_transport_fault),
            .i_now(i_now),
            .i_config_valid(i_config_valid),
            .o_config_ready(o_config_ready),
            .i_session(i_session),
            .i_epoch(i_epoch),
            .i_max_delta(i_max_delta),
            .i_max_wait(i_max_wait),
            .i_max_age(i_max_age),
            .i_ratio_log2(i_ratio_log2),
            .i_hdr_enable(i_hdr_enable),
            .o_config_error(o_config_error),
            .s_frame(s_frame),
            .s_begin_valid(s_begin_valid),
            .s_begin_ready(s_begin_ready),
            .o_begin_accepted(o_begin_accepted),
            .o_capture_slot(o_capture_slot),
            .o_capture_generation(o_capture_generation),
            .o_capture_lease(o_capture_lease),
            .i_finish_valid(i_finish_valid),
            .i_finish_ok(i_finish_ok),
            .o_finish_ready(o_finish_ready),
            .o_pair_valid(o_pair_valid),
            .i_pair_ready(i_pair_ready),
            .o_pair_bank(o_pair_bank),
            .o_pair_id(o_pair_id),
            .i_release_valid(i_release_valid),
            .i_release_bank(i_release_bank),
            .i_release_pair_id(i_release_pair_id),
            .i_read_quiet(i_read_quiet),
            .i_write_quiet(i_write_quiet),
            .i_ticket_released(i_ticket_released),
            .o_release_ready(o_release_ready),
            .i_directory_read_valid(i_directory_read_valid),
            .i_directory_read_slot(i_directory_read_slot),
            .o_directory_read_ready(o_directory_read_ready),
            .m_directory_data(m_directory_data),
            .m_directory_word(m_directory_word),
            .m_directory_valid(m_directory_valid),
            .m_directory_last(m_directory_last),
            .m_directory_ready(m_directory_ready),
            .o_empty(o_empty),
            .o_capture_busy(o_capture_busy),
            .o_exhausted(o_exhausted),
            .o_fault(o_fault),
            .o_bank_states(o_bank_states),
            .o_reject_count(o_reject_count),
            .o_expire_count(o_expire_count),
            .i_begin_member(i_begin_member),
            .i_finish1_valid(i_finish1_valid),
            .i_finish1_ok(i_finish1_ok),
            .o_finish1_ready(o_finish1_ready));
    end else begin:g_serial
        assign o_finish1_ready=1'b0;
        hdr_pair_bank_owner_serial #(.WIDTH(WIDTH),.HEIGHT(HEIGHT),.CAMERA_COUNT(CAMERA_COUNT)) impl(
            .i_clk(i_clk),
            .i_identity_rst_n(i_identity_rst_n),
            .i_stop(i_stop),
            .i_transport_fault(i_transport_fault),
            .i_now(i_now),
            .i_config_valid(i_config_valid),
            .o_config_ready(o_config_ready),
            .i_session(i_session),
            .i_epoch(i_epoch),
            .i_max_delta(i_max_delta),
            .i_max_wait(i_max_wait),
            .i_max_age(i_max_age),
            .i_ratio_log2(i_ratio_log2),
            .i_hdr_enable(i_hdr_enable),
            .o_config_error(o_config_error),
            .s_frame(s_frame),
            .s_begin_valid(s_begin_valid),
            .s_begin_ready(s_begin_ready),
            .o_begin_accepted(o_begin_accepted),
            .o_capture_slot(o_capture_slot),
            .o_capture_generation(o_capture_generation),
            .o_capture_lease(o_capture_lease),
            .i_finish_valid(i_finish_valid),
            .i_finish_ok(i_finish_ok),
            .o_finish_ready(o_finish_ready),
            .o_pair_valid(o_pair_valid),
            .i_pair_ready(i_pair_ready),
            .o_pair_bank(o_pair_bank),
            .o_pair_id(o_pair_id),
            .i_release_valid(i_release_valid),
            .i_release_bank(i_release_bank),
            .i_release_pair_id(i_release_pair_id),
            .i_read_quiet(i_read_quiet),
            .i_write_quiet(i_write_quiet),
            .i_ticket_released(i_ticket_released),
            .o_release_ready(o_release_ready),
            .i_directory_read_valid(i_directory_read_valid),
            .i_directory_read_slot(i_directory_read_slot),
            .o_directory_read_ready(o_directory_read_ready),
            .m_directory_data(m_directory_data),
            .m_directory_word(m_directory_word),
            .m_directory_valid(m_directory_valid),
            .m_directory_last(m_directory_last),
            .m_directory_ready(m_directory_ready),
            .o_empty(o_empty),
            .o_capture_busy(o_capture_busy),
            .o_exhausted(o_exhausted),
            .o_fault(o_fault),
            .o_bank_states(o_bank_states),
            .o_reject_count(o_reject_count),
            .o_expire_count(o_expire_count));
    end endgenerate
endmodule
